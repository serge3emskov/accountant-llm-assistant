# --------------------------------------------------------------------------- ИНН-генерация (для синтетики)


def inn10(base9: str) -> str:
    """10-значный ИНН организации из 9 цифр: дописывает контрольную цифру."""
    w = (2, 4, 10, 3, 5, 9, 4, 6, 8)
    d = sum(int(a) * b for a, b in zip(base9, w)) % 11 % 10
    return base9 + str(d)


def inn12(base10: str) -> str:
    """12-значный ИНН ИП/физлица из 10 цифр: дописывает две контрольные цифры."""
    w1 = (7, 2, 4, 10, 3, 5, 9, 4, 6, 8)
    w2 = (3, 7, 2, 4, 10, 3, 5, 9, 4, 6, 8)
    n1 = sum(int(a) * b for a, b in zip(base10, w1)) % 11 % 10
    s11 = base10 + str(n1)
    n2 = sum(int(a) * b for a, b in zip(s11, w2)) % 11 % 10
    return s11 + str(n2)


